function wrapText(text, maxChars) {
  const lines = [];
  for (const paragraph of String(text || '').toUpperCase().split('\n')) {
    const words = paragraph.split(/\s+/).filter(Boolean);
    let line = '';
    for (const word of words) {
      if (word.length > maxChars) {
        if (line) lines.push(line);
        line = '';
        for (let index = 0; index < word.length; index += maxChars) lines.push(word.slice(index, index + maxChars));
        continue;
      }
      const next = line ? `${line} ${word}` : word;
      if (next.length > maxChars) {lines.push(line); line = word;}
      else line = next;
    }
    if (line) lines.push(line);
  }
  return lines;
}

function drawText(pixels, width, height, {text, x, y, maxWidth, scale = 2, align = 'left'}) {
  const safeScale = Math.max(1, Math.min(8, Math.round(scale)));
  const maxChars = Math.max(1, Math.floor(maxWidth / (6 * safeScale)));
  const lines = wrapText(text, maxChars);
  lines.forEach((line, lineIndex) => {
    const lineWidth = Math.max(0, line.length * 6 * safeScale - safeScale);
    const lineX = align === 'center' ? x + Math.round((maxWidth - lineWidth) / 2) : align === 'right' ? x + maxWidth - lineWidth : x;
    const lineY = y + lineIndex * 9 * safeScale;
    Array.from(line).forEach((character, charIndex) => {
      const glyph = FONT[character] || FONT[' '];
      glyph.forEach((row, rowIndex) => {
        for (let column = 0; column < 5; column += 1) {
          if (row[column] !== '1') continue;
          const px = lineX + charIndex * 6 * safeScale + column * safeScale;
          const py = lineY + rowIndex * safeScale;
          for (let dy = 0; dy < safeScale; dy += 1) {
            for (let dx = 0; dx < safeScale; dx += 1) {
              const targetX = px + dx;
              const targetY = py + dy;
              if (targetX >= 0 && targetX < width && targetY >= 0 && targetY < height) pixels[targetY * width + targetX] = 1;
            }
          }
        }
      });
    });
  });
}

